const {chromium}=require('playwright');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,locale:'zh-CN',timezoneId:'Asia/Shanghai',reducedMotion:'reduce'});
  await page.clock.install({time:new Date('2026-10-19T10:00:00+08:00')});
  await page.goto(pathToFileURL(path.resolve(__dirname,'../artifacts/weiji-preview.html')).href);
  await page.screenshot({path:path.resolve(__dirname,'../artifacts/preview-home.png')});
  await page.evaluate(()=>WeijiTheme.setMode('dark'));
  await page.screenshot({path:path.resolve(__dirname,'../artifacts/preview-dark.png')});
  await page.evaluate(()=>WeijiTheme.setMode('light'));
  await page.locator('[data-page="stats"]').click();
  await page.screenshot({path:path.resolve(__dirname,'../artifacts/preview-stats.png')});
  await page.locator('[data-page="records"]').click();
  await page.screenshot({path:path.resolve(__dirname,'../artifacts/preview-records.png')});
  await page.locator('.add-button').click();
  await page.locator('#form-time').fill('09:30');await page.locator('#form-duration').fill('18');
  await page.locator('[data-action="add-view"]').click();
  await page.locator('#form-title').fill('想记住的片段');
  await page.locator('[data-action="toggle-tag"][data-id="tag_plot"]').click();
  await page.locator('[data-action="toggle-tag"][data-id="tag_slow"]').click();
  const image=await page.evaluate(async()=>{
    const img=new Image();img.src=WeijiPreviewCovers['covers/1.svg'];await img.decode();
    const canvas=document.createElement('canvas');canvas.width=400;canvas.height=500;
    canvas.getContext('2d').drawImage(img,0,0,400,500);
    return canvas.toDataURL('image/jpeg',.88).split(',')[1];
  });
  await page.locator('#image-input').setInputFiles({name:'example.jpg',mimeType:'image/jpeg',buffer:Buffer.from(image,'base64')});
  await page.waitForFunction(()=>document.querySelectorAll('.image-cell').length===1);
  await page.locator('#toast').waitFor({state:'hidden'});
  await page.locator('.sheet').evaluate(el=>el.scrollTop=0);
  await page.screenshot({path:path.resolve(__dirname,'../artifacts/preview-add.png')});
  await page.locator('.sheet').evaluate(el=>el.scrollTop=el.scrollHeight);
  await page.screenshot({path:path.resolve(__dirname,'../artifacts/preview-watch.png')});
  await page.locator('#save-record').click();
  await page.locator('[data-page="home"]').click();await page.locator('.elapsed-last').click();
  await page.locator('#toast').waitFor({state:'hidden'});
  await page.screenshot({path:path.resolve(__dirname,'../artifacts/preview-combined.png')});
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
